import type { CourseDraft } from "@/lib/admin/draft-store";

/**
 * Draft -> committed source. The editor cannot write to the repo (a static
 * Next page has no filesystem), so this is the bridge: it prints exactly the
 * three edits a course needs, and the human commits them.
 *
 * Output is deliberately plain TS with no imports beyond the schema types, so
 * what is generated is what a person would have written by hand.
 */

const quote = (value: string) => `      ${JSON.stringify(value)},`;

function contentSource(draft: CourseDraft): string {
  const c = draft.content;
  // A name containing `*/` would close the generated block comment early and
  // turn otherwise valid output into a syntax error.
  const safeName = draft.meta.nama
    .replace(/\*\//g, "* /")
    .replace(/\s+/g, " ")
    .trim();
  const anatomi = c.anatomi
    .map(
      (s) =>
        `    {\n      judul: ${JSON.stringify(s.judul)},\n      teks: ${JSON.stringify(s.teks)},\n    },`,
    )
    .join("\n");
  const contoh = c.contohIsi
    .map(
      (s) =>
        `    { text: ${JSON.stringify(s.text)}, berbahaya: ${s.berbahaya} },`,
    )
    .join("\n");
  const checklist = c.checklist.map((s) => quote(s)).join("\n");
  const kuis = c.kuis
    .map((q) => {
      const options = q.options
        .map(
          (o) =>
            `        { id: ${JSON.stringify(o.id)}, label: ${JSON.stringify(o.label)} },`,
        )
        .join("\n");
      return `    {
      id: ${JSON.stringify(q.id)},
      prompt: ${JSON.stringify(q.prompt)},
      options: [
${options}
      ],
      correctId: ${JSON.stringify(q.correctId)},
      rationale: ${JSON.stringify(q.rationale)},
    },`;
    })
    .join("\n");
  const lapor = c.lapor.map((s) => quote(s)).join("\n");

  return `import type { ModuleContent } from "@/data/modul-schema";

/**
 * Modul ${String(draft.no).padStart(2, "0")} — ${safeName}.
 * Generated by /admin, then reviewed and committed by a human.
 */
export const MODUL_${String(draft.no).padStart(2, "0")} = {
  no: ${draft.no},
  anatomi: [
${anatomi}
  ],
  contohJudul: ${JSON.stringify(c.contohJudul)},
  contohJenis: ${JSON.stringify(c.contohJenis ?? "pesan")},
  contohSumber: ${JSON.stringify(c.contohSumber ?? "")},
  contohIsi: [
${contoh}
  ],
  checklist: [
${checklist}
  ],
  kuis: [
${kuis}
  ],
  lapor: [
${lapor}
  ],
  scenarioId: ${c.scenarioId === null ? "null" : JSON.stringify(c.scenarioId)},
} satisfies ModuleContent;
`;
}

function kurikulumEntry(draft: CourseDraft): string {
  return `  ${draft.no}: MODUL_${String(draft.no).padStart(2, "0")},`;
}

function kurikulumImport(draft: CourseDraft): string {
  return `import { MODUL_${String(draft.no).padStart(2, "0")} } from "./modul-${String(draft.no).padStart(2, "0")}";`;
}

function modusEntry(draft: CourseDraft): string {
  const m = draft.meta;
  // `modus.json` is JSON, so this must be strict JSON — quoted keys and no
  // trailing commas — or pasting it breaks the file for Stream A.
  const entry = {
    id: slugify(m.nama, draft.no),
    no: draft.no,
    nama: m.nama,
    laporan: m.laporan,
    laporanNote: m.laporanNote,
    kerugian: m.kerugian,
    ciri: m.ciri,
    level: m.level,
    modulStatus: "lengkap",
    scenarioId: null,
    scenarioPlanned: null,
    detectors: [],
  };
  return JSON.stringify(entry, null, 2)
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

/** Stable id from the course name, with the number as a tiebreaker. */
export function slugify(name: string, no: number): string {
  const base = name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return base || `course-${no}`;
}

export interface ExportBundle {
  fileName: string;
  moduleFile: string;
  kurikulumImport: string;
  kurikulumEntry: string;
  modusEntry: string;
  /** True when the course number is past the original twelve. */
  requiresUnboundedList: boolean;
}

export function exportCourse(draft: CourseDraft): ExportBundle {
  const padded = String(draft.no).padStart(2, "0");
  return {
    fileName: `modul-${padded}.ts`,
    moduleFile: contentSource(draft),
    kurikulumImport: kurikulumImport(draft),
    kurikulumEntry: kurikulumEntry(draft),
    modusEntry: modusEntry(draft),
    requiresUnboundedList: draft.no > 12,
  };
}
